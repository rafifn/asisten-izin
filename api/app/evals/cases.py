"""Eval case shape and loader. `evals/cases.yaml` is validated against these models."""

from pathlib import Path
from typing import Literal

import yaml
from pydantic import BaseModel, ConfigDict, model_validator

from app.pipeline.schemas import Attributes

REPO_ROOT = Path(__file__).resolve().parents[3]
CASES_PATH = REPO_ROOT / "evals" / "cases.yaml"
DATA_DIR = REPO_ROOT / "data"


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


class ExpectedActivity(_Strict):
    primary: str
    acceptable: list[str]
    attributes: Attributes

    @model_validator(mode="after")
    def _primary_acceptable(self) -> "ExpectedActivity":
        if self.primary not in self.acceptable:
            raise ValueError(f"primary {self.primary} must be listed in acceptable")
        return self


class Expect(_Strict):
    scope: Literal["in", "partial", "out"]
    # Vague cases: the first pass must ask for clarification; the second pass (each question
    # answered with its first option) is scored for scope only, since its codes are not knowable.
    clarify: bool = False
    activities: list[ExpectedActivity] = []
    # Generated by evals/gen_expected.py from the rules engine; committed as literals.
    permits: list[str] | None = None
    risk: dict[str, str] | None = None


class Case(_Strict):
    id: str
    description: str
    answers: dict[str, str] | None = None
    expect: Expect


def load_cases(path: Path = CASES_PATH) -> list[Case]:
    raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    cases = [Case.model_validate(c) for c in raw]
    ids = [c.id for c in cases]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate case ids")
    return cases
